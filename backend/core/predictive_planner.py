    def __init__(self):
        self._topic_cache: dict[str, list[ResearchTopic]] = {}  # user_id -> topics

    # ------------------------------------------------------------------
    # Predict Next Topics
    # ------------------------------------------------------------------
    async def predict_next_topics(
        self,
        user_id: str,
        session_history: list[dict[str, Any]],
    ) -> PredictionResult:
        """Analyze session history and predict what the user might research next.

        Args:
            user_id: The user's ID.
            session_history: List of session dicts with 'query', 'topics', 'tags', 'created_at'.

        Returns:
            PredictionResult with predicted topics, gaps, and insights.
        """
        # Extract topics from history
        topics = self._extract_topics_from_history(session_history)
        self._topic_cache[user_id] = topics

        # Predict next topics using transition patterns
        predicted = self._predict_from_transitions(topics)

        # Identify knowledge gaps
        gaps = self._identify_gaps(topics)

        # Generate research score
        research_score = self._calculate_research_score(session_history)

        # Generate insights
        insights = self._generate_insights(topics, session_history)

        return PredictionResult(
            predicted_topics=predicted[:10],
            knowledge_gaps=gaps,
            research_score=research_score,
            insights=insights,
        )

    # ------------------------------------------------------------------
    # Generate Research Plan
    # ------------------------------------------------------------------
    async def generate_research_plan(
        self,
        topic: str,
        depth: str = "default",
        user_context: Optional[dict[str, Any]] = None,
    ) -> ResearchPlan:
        """Generate a structured research plan for a given topic.

        Args:
            topic: The research topic.
            depth: Plan depth — "quick" (3 milestones) or "default" (6 milestones).
            user_context: Optional context about user's existing knowledge.

        Returns:
            ResearchPlan with milestones and dependencies.
        """
        template = self._PLAN_TEMPLATES.get(depth, self._PLAN_TEMPLATES["default"])
        milestones = []

        for i, m in enumerate(template["milestones"]):
            queries = [q.format(topic=topic) for q in m.get("queries", [])]
            deps = [milestones[i - 1].title] if i > 0 else []

            milestones.append(ResearchMilestone(
                title=m["title"],
                description=m["description"],
                estimated_time=m.get("time", "1-2 hours"),
                dependencies=deps,
                queries=queries,
                order=i + 1,
            ))

        # Add prerequisites based on user context
        prerequisites = []
        if user_context and user_context.get("known_topics"):
            known = set(user_context["known_topics"])
            topic_words = set(topic.lower().split())
            if not topic_words & known:
                prerequisites.append(f"Basic understanding of {topic} concepts")

        plan = ResearchPlan(
            title=f"Research Plan: {topic}",
            description=f"A structured {depth} research plan for '{topic}' with "
                       f"{len(milestones)} milestones and estimated {template['total_time']} of research.",
            milestones=milestones,
            estimated_total_time=template["total_time"],
            difficulty=template["difficulty"],
            prerequisites=prerequisites,
            topic=topic,
        )

        logger.info("research_plan_generated", topic=topic, milestones=len(milestones), depth=depth)
        return plan

    # ------------------------------------------------------------------
    # Suggest Research Plans
    # ------------------------------------------------------------------
    async def suggest_research_plans(
        self,
        user_id: str,
        session_history: list[dict[str, Any]],
    ) -> list[ResearchPlan]:
        """Suggest research plans based on predicted topics.

        Returns top 3 suggested plans with milestones.
        """
        prediction = await self.predict_next_topics(user_id, session_history)
        plans = []

        for topic in prediction.predicted_topics[:3]:
            plan = await self.generate_research_plan(topic.topic, depth="default")
            plan.description = f"Suggested based on your interest in {topic.topic} " \
                             f"(confidence: {topic.confidence:.0%})"
            plans.append(plan)

        return plans

    # ------------------------------------------------------------------
    # Internal Methods
    # ------------------------------------------------------------------
    def _extract_topics_from_history(self, sessions: list[dict]) -> list[ResearchTopic]:
        """Extract and aggregate research topics from session history."""
        topic_map: dict[str, ResearchTopic] = {}

        for session in sessions:
            # Extract from query text
            query = session.get("query", "")
            tags = session.get("tags", [])
            topics_raw = session.get("topics", [])
            session_id = session.get("id", "")

            # Use tags as topic signals
            all_topics = topics_raw + [t.lower().strip() for t in tags if isinstance(t, str)]

            # Also extract from query (simple keyword extraction)
            if query:
                words = query.lower().split()
                # Skip common words
                skip = {"what", "how", "why", "is", "are", "the", "a", "an", "for", "to", "of", "in", "and", "or", "on", "with", "about", "latest", "best", "new"}
                meaningful = [w for w in words if w not in skip and len(w) > 3]
                # Take bigrams as topics
                for i in range(len(meaningful) - 1):
                    bigram = f"{meaningful[i]} {meaningful[i+1]}"
                    all_topics.append(bigram)

            for topic in all_topics:
                topic = topic.lower().strip()
                if not topic or len(topic) < 3:
                    continue

                if topic in topic_map:
                    topic_map[topic].frequency += 1
                    topic_map[topic].last_accessed = max(
                        topic_map[topic].last_accessed,
                        session.get("created_at", time.time())
                    )
                    if session_id and session_id not in topic_map[topic].source_sessions:
                        topic_map[topic].source_sessions.append(session_id)
                else:
                    topic_map[topic] = ResearchTopic(
                        topic=topic,
                        frequency=1,
                        last_accessed=session.get("created_at", time.time()),
                        source_sessions=[session_id] if session_id else [],
                    )

        # Sort by frequency and recency
        topics = sorted(topic_map.values(), key=lambda t: t.frequency * 2 + (t.last_accessed / 1e10), reverse=True)
        return topics[:30]

    def _predict_from_transitions(self, topics: list[ResearchTopic]) -> list[ResearchTopic]:
        """Predict next topics using the transition adjacency map."""
        predicted: list[ResearchTopic] = []
        existing_topics = {t.topic for t in topics}

        for topic in topics[:10]:
            # Look for matching transition patterns
            for key, transitions in self._TOPIC_TRANSITIONS.items():
                if key in topic.topic or topic.topic in key:
                    for next_topic, confidence in transitions:
                        if next_topic not in existing_topics:
                            predicted.append(ResearchTopic(
                                topic=next_topic,
                                confidence=confidence * (topic.frequency / max(topics[0].frequency, 1)),
                                related_topics=[topic.topic],
                            ))
                            existing_topics.add(next_topic)

        # Also predict based on topic co-occurrence
        if len(topics) >= 2:
            top_topics = [t.topic for t in topics[:5]]
            predicted.append(ResearchTopic(
                topic=f"{' and '.join(top_topics[:2])} intersection",
                confidence=0.4,
                related_topics=top_topics[:2],
            ))

        predicted.sort(key=lambda t: t.confidence, reverse=True)
        return predicted

    def _identify_gaps(self, topics: list[ResearchTopic]) -> list[KnowledgeGap]:
        """Identify knowledge gaps based on research patterns."""
        gaps: list[KnowledgeGap] = []
        topic_set = {t.topic for t in topics}

        for pattern in self._GAP_PATTERNS:
            # Check if any trigger topics are in the user's history
            triggered = any(t in topic_set for t in pattern["trigger_topics"])
            # Check if the gap topic is already covered
            gap_covered = pattern["gap_topic"] in topic_set

            if triggered and not gap_covered:
                gaps.append(KnowledgeGap(
                    topic=pattern["gap_topic"],
                    reason=pattern["reason"],
                    priority="high" if len([t for t in pattern["trigger_topics"] if t in topic_set]) >= 2 else "medium",
                    suggested_queries=pattern["queries"],
                    related_existing_topics=[t for t in pattern["trigger_topics"] if t in topic_set],
                ))

        return gaps

    def _calculate_research_score(self, sessions: list[dict]) -> float:
        """Calculate a research activity score (0-1)."""
        if not sessions:
            return 0.0

        # Factors: number of sessions, topic diversity, recency, depth
        num_sessions = min(len(sessions), 50) / 50  # 0-1
        topic_diversity = len(set(
            tag for s in sessions for tag in s.get("tags", [])
        )) / 20  # normalize
        recency = 1.0 if sessions else 0.0

        score = (num_sessions * 0.4 + min(topic_diversity, 1.0) * 0.3 + recency * 0.3)
        return round(min(score, 1.0), 3)

    def _generate_insights(self, topics: list[ResearchTopic], sessions: list[dict]) -> list[str]:
        """Generate actionable research insights."""
        insights = []

        if topics:
            top = topics[0]
            insights.append(f"Your most researched topic is '{top.topic}' with {top.frequency} sessions.")

        if len(topics) >= 3:
            insights.append(f"You've explored {len(topics)} distinct research topics.")

        # Check for focus vs breadth
        if topics and topics[0].frequency > 5:
            insights.append(f"You show deep focus on '{topics[0].topic}' — consider exploring adjacent areas.")
        elif len(topics) > 10:
            insights.append("You have broad research interests — a focused deep dive might yield insights.")

        return insights


